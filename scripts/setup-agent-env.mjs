#!/usr/bin/env node
/**
 * Create `.env.agent`, the environment agent sessions run in.
 *
 * The agent environment is a second, disposable database plus a probe user. It exists so an
 * agent never reads or writes `pictures_writers_dev`, which can hold a restored production
 * dump: real users, real content, real live session tokens. The values here are generated
 * locally and must never be copied from production.
 *
 *   node scripts/setup-agent-env.mjs
 *
 * Idempotent: an existing `.env.agent` is left untouched. Delete the file to rotate.
 */

import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const devEnvPath = join(repoRoot, ".env");
const agentEnvPath = join(repoRoot, ".env.agent");

const DEV_DATABASE = "pictures_writers_dev";
const AGENT_DATABASE = "pictures_writers_agent";
const PROBE_EMAIL = "probe@agent.local";

function readEnvValue(text, key) {
  const line = text.split(/\r?\n/).find((candidate) => candidate.startsWith(`${key}=`));

  if (!line) {
    throw new Error(`${key} is missing from .env; the agent database URL is derived from it.`);
  }

  return line.slice(key.length + 1).trim().replace(/^["']|["']$/g, "");
}

function secret() {
  return randomBytes(32).toString("base64url");
}

if (existsSync(agentEnvPath)) {
  console.log(".env.agent already exists; delete it to regenerate.");
  process.exit(0);
}

if (!existsSync(devEnvPath)) {
  throw new Error("No .env found; copy the development environment file first.");
}

const devUrl = readEnvValue(readFileSync(devEnvPath, "utf8"), "DATABASE_URL");

if (!devUrl.includes(`/${DEV_DATABASE}`)) {
  throw new Error(`.env DATABASE_URL does not point at ${DEV_DATABASE}; refusing to derive the agent URL.`);
}

// 127.0.0.1 rather than localhost: on Windows localhost can resolve to ::1, which the
// published container port does not forward.
const agentUrl = devUrl
  .replace(new RegExp(`/${DEV_DATABASE}(\\?|$)`), `/${AGENT_DATABASE}$1`)
  .replace("@localhost:", "@127.0.0.1:");

writeFileSync(
  agentEnvPath,
  `# Agent environment: a disposable database and a probe user, never production values.
# Generated by scripts/setup-agent-env.mjs. Delete the file to rotate every secret in it.
DATABASE_URL=${agentUrl}
BETTER_AUTH_URL=http://localhost:3000
NEXT_PUBLIC_APP_URL=http://localhost:3000
BETTER_AUTH_SECRET=${secret()}
SCHEDULED_PUBLICATION_SECRET=${secret()}
MEDIA_STORAGE_DRIVER=local
UPLOADTHING_TOKEN=
PROBE_ADMIN_EMAIL=${PROBE_EMAIL}
PROBE_ADMIN_PASSWORD=${secret()}
PROBE_PAGE_ROOT_ID=
`,
  "utf8",
);

console.log(`wrote .env.agent (database ${agentUrl.replace(/^[^@]*@/, "")}, probe user ${PROBE_EMAIL})`);
console.log("next: npm run agent:seed");
