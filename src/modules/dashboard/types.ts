import type { LucideIcon } from "lucide-react";
import type { ComponentType } from "react";

/**
 * The discrete widget sizes, in ascending order. The single source of truth for
 * the vocabulary: the type, the size menu, and the persistence schema all derive
 * from it.
 */
export const WIDGET_SIZES = ["small", "medium", "full"] as const;

/**
 * Discrete size token for a Dashboard widget, expressed in grid columns on the
 * dashboard's six-column `md` grid. A definition declares a default size and
 * the backoffice user may override it per instance.
 */
export type WidgetSize = (typeof WIDGET_SIZES)[number];

/**
 * The fascia a Dashboard widget belongs to. Operational widgets surface what
 * needs attention now and ignore the shared date range; analytics widgets are
 * Trend instances governed by it. Defaults to `operational`.
 */
export type WidgetCategory = "operational" | "analytics";

/**
 * Config carried by a Dashboard widget instance. The concrete shape is owned by
 * the widget definition's `configSchema`; it is stored as opaque JSON so a
 * definition can become configurable without a model change.
 */
export type WidgetConfig = Record<string, unknown> | null;

/** One choice offered by a configurable widget's select field. */
export interface WidgetConfigOption {
  value: string;
  label: string;
}

/**
 * A field in a widget's config form, generated by the definition's config
 * schema and rendered by the config popover. Discriminated by `type` so a new
 * kind can be added alongside `select` later.
 */
export interface WidgetConfigSelectField {
  type: "select";
  /** The key written into the instance config. */
  name: string;
  label: string;
  options: WidgetConfigOption[];
}

export type WidgetConfigField = WidgetConfigSelectField;

/** The form a configurable widget exposes, generated from its definition. */
export interface WidgetConfigSchema {
  fields: WidgetConfigField[];
}

/**
 * Data available when a definition's config schema is resolved for the current
 * user, so a widget can build its choices from permission-scoped data. The
 * Trend's metric picker builds its options from the metrics the user may read.
 */
export interface WidgetConfigContext {
  metrics: MetricSummary[];
}

/**
 * A definition's config contract, resolved against the current user's context.
 * A function (rather than a static object) because a definition's options can
 * depend on what the user is permitted to see.
 */
export type WidgetConfigSchemaResolver = (
  context: WidgetConfigContext,
) => WidgetConfigSchema;

/**
 * An instance of a Widget definition as placed on a user's Dashboard layout.
 *
 * `key` is a stable instance key: registry defaults use deterministic keys
 * (e.g. `drafts`) while user-created instances get a generated key, so
 * reordering or reconfiguring an instance never changes its identity.
 */
export interface DashboardWidgetInstance {
  key: string;
  definitionId: string;
  config?: WidgetConfig;
  hidden?: boolean;
  /**
   * The instance's grid size. Optional: when absent the definition's
   * `defaultSize` applies, so a saved layout stays valid as defaults change.
   */
  size?: WidgetSize;
}

/**
 * Props every Dashboard widget component receives. `instance` gives the widget
 * access to its stable key and its per-instance config.
 */
export interface WidgetComponentProps {
  instance: DashboardWidgetInstance;
}

/**
 * The code-defined catalog entry describing one kind of Dashboard widget.
 * Definitions are code, not database rows; the Dashboard widget is an instance
 * of a definition.
 */
export interface WidgetDefinition {
  id: string;
  title: string;
  description?: string;
  icon: LucideIcon;
  /**
   * The area permission that gates the widget. Optional: a widget that derives
   * its availability from other sources (e.g. the metrics a user may read)
   * declares none and is always considered permitted.
   */
  permission?: string;
  /** The grid size a freshly added instance of this definition starts at. */
  defaultSize: WidgetSize;
  /** Which dashboard fascia the definition belongs to. Defaults to operational. */
  category?: WidgetCategory;
  component: ComponentType<WidgetComponentProps>;
  /**
   * Optional config contract for configurable widgets. A definition without one
   * is not configurable and its card shows no gear in edit mode.
   */
  configSchema?: WidgetConfigSchemaResolver;
  /** Config a newly added instance of this definition starts with. */
  defaultConfig?: WidgetConfig;
}

/** The persisted per-user document: the list of Dashboard widget instances. */
export type DashboardWidgets = DashboardWidgetInstance[];

/** One point of a Metric's time series: a bucket label and its value. */
export interface MetricPoint {
  label: string;
  value: number;
}

/**
 * A Metric's time series over the requested range: the buckets plus the current
 * total and its growth against the previous comparable period.
 */
export interface MetricSeries {
  points: MetricPoint[];
  total: number;
  percentageGrowth: number;
}

/**
 * A named, permission-scoped time series exposed by the server-side metric
 * registry. The Trend widget renders exactly one Metric at a time.
 */
export interface Metric {
  id: string;
  label: string;
  permission: string;
  timeSeries: (from: Date, to: Date) => Promise<MetricSeries>;
}

/** The client-facing summary of a Metric: enough to list and select it. */
export interface MetricSummary {
  id: string;
  label: string;
}
